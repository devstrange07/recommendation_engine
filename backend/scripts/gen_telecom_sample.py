def _product(
    idx: int,
    name: str,
    category: str,
    description: str,
    plan_name: str,
    feature_text: str,
    amount: int,
    unit: str,
) -> dict:
    return {
        "id": f"tel_{idx:03d}",
        "name": name,
        "category": category,
        "unit": unit,
        "kb_article": None,
        "description": description,
        "plans": [
            {
                "id": "plan_1",
                "name": plan_name,
                "feature_text": feature_text,
                "billing_period": "one_time",
                "price_lists": [
                    {
                        "name": "IN-inr",
                        "country": "IN",
                        "currency": "INR",
                        "amount": amount,
                    }
                ],
            }
        ],
        "updated_at": UPDATED_AT,
    }


def build_catalog(target_total: int) -> tuple[list[ProductTuple], list[ProductTuple]]:
    acc_target = round(target_total * 0.20)
    phone_target = target_total - acc_target

    phones = list(BASE_PHONES)
    accessories = list(BASE_ACCESSORIES)
    seen = {item[0] for item in phones + accessories}

    if target_total > 200:
        for item in expand_phones():
            if len(phones) >= phone_target:
                break
            if item[0] not in seen:
                phones.append(item)
                seen.add(item[0])
        for item in expand_accessories():
            if len(accessories) >= acc_target:
                break
            if item[0] not in seen:
                accessories.append(item)
                seen.add(item[0])

    if len(phones) != phone_target:
        raise ValueError(
            f"phone count mismatch: got {len(phones)}, need {phone_target} "
            f"(add more expansions)"
        )
    if len(accessories) != acc_target:
        raise ValueError(
            f"accessory count mismatch: got {len(accessories)}, need {acc_target} "
            f"(add more expansions)"
        )
    return phones, accessories


def catalog_to_json(phones: list[ProductTuple], accessories: list[ProductTuple]) -> list[dict]:
    products: list[dict] = []
    idx = 1
    for name, cat, desc, plan, feat, amount in phones:
        products.append(_product(idx, name, cat, desc, plan, feat, amount, unit="device"))
        idx += 1
    for name, cat, desc, plan, feat, amount in accessories:
        products.append(_product(idx, name, cat, desc, plan, feat, amount, unit="piece"))
        idx += 1
    return products


def validate(products: list[dict], target_total: int) -> None:
    assert len(products) == target_total
    names = [p["name"] for p in products]
    assert len(names) == len(set(names)), "duplicate product names"
    cats = Counter(p["category"] for p in products)
    acc_target = round(target_total * 0.20)
    assert cats["Electronics/Accessories"] == acc_target
    foldables = cats["Electronics/Foldables"]
    phones = target_total - acc_target
    fold_target = round(phones * 0.075)  # ~30 for 500
    assert foldables >= max(12, fold_target - 5)
    assert foldables <= fold_target + 5
    for p in products:
        plan = p["plans"][0]
        assert plan["billing_period"] == "one_time"
        assert plan["price_lists"][0]["currency"] == "INR"
        assert p["updated_at"] == UPDATED_AT


def write_catalog(target_total: int) -> Path:
    phones, accessories = build_catalog(target_total)
    products = catalog_to_json(phones, accessories)
    validate(products, target_total)

    out = SAMPLES_DIR / f"telecom_india_{target_total}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"products": products}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    cats = Counter(p["category"] for p in products)
    print(f"Wrote {out}")
    print(
        f"total={len(products)} smartphones={cats['Electronics/Smartphones']} "
        f"foldables={cats['Electronics/Foldables']} "
        f"accessories={cats['Electronics/Accessories']}"
    )
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate India telecom sample JSON")
    parser.add_argument("--count", type=int, default=200, choices=[200, 500])
    args = parser.parse_args()
    write_catalog(args.count)


if __name__ == "__main__":
    main()
